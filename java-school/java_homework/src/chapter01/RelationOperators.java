package chapter01;

public class RelationOperators {

	public static void main(String[] args) {
		int w = 25,x = 3;
		boolean y = w < x;
		boolean z = w >= w * 2 - x * 9;
		boolean cc = 'b' > 'a';
		System.out.println("w < x = "+ y);
		System.out.println("z = "+ z);
		System.out.println("cc = "+ cc);
	}
}
