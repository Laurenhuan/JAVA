package chapter01;

public class EscapeCharacter {

	public static void main(String[] args) {
		System.out.println('\'');
		System.out.println("\\\'");
		System.out.println("java\n\r语\b言");
		System.out.println("java\r语言");
		System.out.println("java\t语言");
		System.out.println("\\java语言\\");
		System.out.println("\'java语言\'");
		System.out.println("\"java语言\"");

	}
}
